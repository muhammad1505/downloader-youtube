package id.local.tubeflow.core

import org.junit.Assert.*
import org.junit.Test

class CollectionCreditTest {
    private fun entry(title: String, artist: String = "", uploader: String = "Label") = PlaylistEntry(title,title,200,"https://youtu.be/example",uploader,artist)
    private fun meta(title: String, artist: String = "") = VideoMetadata(title,"Label",200,"","https://youtu.be/example",artist=artist)
    private fun learn(vararg entries: PlaylistEntry) = CollectionCredit.learn(PlaylistMetadata("Mix", "https://youtube.com/playlist?list=RDexample", entries.toList()))
    @Test fun provenArtistPropagatesOnlyThroughExactTitleCredit() {
        val credits=learn(entry("Song One","Denny Caknan"))
        for (title in listOf("Denny Caknan - PINGAL", "PINGAL - Denny Caknan")) {
            val resolved=credits.apply(meta(title))
            assertEquals("Denny Caknan",resolved.artist)
            assertEquals("PINGAL - Denny Caknan",TitleSplit.display(TitleSplit.identify(resolved.title,metadataArtist=resolved.artist)))
        }
        assertEquals("",credits.apply(meta("Denny Caknan Jr - PINGAL")).artist)
        assertEquals("Adele",learn(entry("Adele","Adele")).apply(meta("Hello - Adele")).artist)
    }
    @Test fun compactChannelAliasCorroboratesFullTitleCredit() {
        assertEquals("Denny Caknan",TitleSplit.identify("Denny Caknan - PINGAL",channel="DennyCaknanOfficial").artist)
        assertEquals("Adele",TitleSplit.identify("Hello - Adele",channel="AdeleVEVO").artist)
        assertNull(TitleSplit.identify("Hello",channel="AdeleVEVO").artist)
    }
    @Test fun explicitCollaborationWorksInEitherOrderButAmbiguityStaysUnknown() {
        for (raw in listOf("Denny Caknan x Happy Asmara - SATRU 2", "SATRU 2 - Denny Caknan ft. Happy Asmara")) {
            val id=TitleSplit.identify(raw); assertEquals("SATRU 2",id.title); assertNotNull(id.artist)
        }
        assertNull(TitleSplit.identify("Artist One x Artist Two - Other One x Other Two").artist)
        val challenge="CREATOR ONE vs CREATOR TWO - Challenge"
        val video=DownloadJob("v","https://youtu.be/example","Video",MediaMode.VIDEO,"mp4",720,0).withMetadata(meta(challenge))
        assertEquals(challenge,video.title); assertEquals("",video.artist)
        val sigar=TitleSplit.identify("DENNY CAKNAN FEAT. NIKEN SALINDRY - SIGAR (OFFICIAL LIVE MUSIC VIDEO) | DC MUSIK")
        assertEquals("SIGAR",sigar.title)
        assertEquals("LIVE",sigar.versionTag)
        assertEquals("DENNY CAKNAN FEAT. NIKEN SALINDRY",sigar.artist)
    }
    @Test fun repeatedSongTitlesAndLabelsAreNotArtistEvidence() {
        val credits=learn(entry("LAMUNAN - Singer One"),entry("LAMUNAN - Singer Two"),entry("Label - Song One"),entry("Label - Song Two"))
        assertEquals("",credits.apply(meta("LAMUNAN - Singer Three")).artist)
        assertEquals("",credits.apply(meta("Label - Song Three")).artist)
    }
    @Test fun remixNeverReceivesCollectionArtist() {
        val credits=learn(entry("Song One","Denny Caknan"))
        assertEquals("",credits.apply(meta("DJ Denny Caknan - Song (Remix)")).artist)
        assertEquals("",credits.apply(meta("Denny Caknan - Song (Slowed Reverb)")).artist)
        assertEquals("",credits.apply(meta("Denny Caknan - Song (Cover)")).artist)
    }
    @Test fun individualMetadataWinsOverSharedCredits() {
        val credits=learn(entry("Song One","Denny Caknan"))
        assertEquals("Original Artist",credits.apply(meta("Denny Caknan - Song","Original Artist")).artist)
        assertNull(TitleSplit.identify("Song",metadataArtist="Unknown Artist").artist)
        assertNull(TitleSplit.identify("Song",channel="Various Artists - Topic").artist)
    }
    @Test fun autogeneratedAlbumRequiresOneCorroboratedPerformerAndRejectsVariousArtists() {
        val album=PlaylistMetadata("Album", "https://youtube.com/playlist?list=OLAK5uy_example",listOf(entry("Song One","Adele"),entry("Song Two")),channel="Adele - Topic")
        assertEquals("Adele",CollectionCredit.learn(album).apply(meta("Song Two")).artist)
        assertEquals("",CollectionCredit.learn(album.copy(channel="Unrelated owner")).apply(meta("Song Two")).artist)
        assertEquals("",CollectionCredit.learn(album.copy(entries=listOf(entry("One","Various Artists")),channel="Various Artists")).apply(meta("Song Two")).artist)
    }
    @Test fun refreshedSourceKeepsSharedCreditOnlyWhenStillCorroborated() {
        val credits=learn(entry("One","Denny Caknan"))
        val job=DownloadJob("id","https://youtu.be/example","Video",MediaMode.AUDIO,"mp3",0,128,subfolder="mix-denny-caknan",autoFolder="collection")
            .withMetadata(credits.apply(meta("Denny Caknan - PINGAL")))
        assertEquals("Denny Caknan",job.withMetadata(meta("Denny Caknan - PINGAL")).artist)
        assertEquals("",job.withMetadata(meta("Unrelated title")).artist)
        assertEquals("",job.withMetadata(meta("Denny Caknan - PINGAL (Cover)")).artist)
        assertEquals("mix-denny-caknan",job.withMetadata(meta("Unrelated title")).subfolder)
    }
    @Test fun verifiedSeedCanCorroborateOtherMixEntriesWithoutSelectionDependence() {
        val playlist=PlaylistMetadata("Mix", "https://youtube.com/playlist?list=RDexample",emptyList(),seedMetadata=meta("Seed","Denny Caknan"))
        assertEquals("Denny Caknan",CollectionCredit.learn(playlist).apply(meta("PINGAL - Denny Caknan")).artist)
    }
}
